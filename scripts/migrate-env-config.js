#!/usr/bin/env node

/**
 * Migration script to convert from JSON-based environment configuration
 * to the new prefixed environment variables approach
 */

const fs = require('fs');
const path = require('path');

// ANSI color codes for console output
const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  magenta: '\x1b[35m',
  cyan: '\x1b[36m',
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

function logError(message) {
  log(`❌ ${message}`, 'red');
}

function logSuccess(message) {
  log(`✅ ${message}`, 'green');
}

function logInfo(message) {
  log(`ℹ️  ${message}`, 'blue');
}

function logWarning(message) {
  log(`⚠️  ${message}`, 'yellow');
}

/**
 * Parse JSON environment configuration
 */
function parseJsonConfig(jsonString) {
  try {
    // Remove spaces and parse JSON
    const cleanJson = jsonString.replace(/\s/g, '');
    return JSON.parse(cleanJson);
  } catch (error) {
    throw new Error(`Failed to parse JSON configuration: ${error.message}`);
  }
}

/**
 * Convert environment configuration to prefixed variables
 */
function convertToPrefixedVariables(environments) {
  const variables = {
    ENVIRONMENT_MODE: 'multi',
    DEFAULT_ENVIRONMENT: Object.keys(environments)[0] || 'production',
  };

  Object.entries(environments).forEach(([envName, config]) => {
    const prefix = envName.toUpperCase();

    // Map configuration keys to environment variable names
    const mappings = {
      baseUrl: 'API_BASE_URL',
      masterKey: 'MASTER_KEY',
      lokiUrl: 'LOKI_URL',
      promUrl: 'PROMETHEUS_URL',
      namespace: 'NAMESPACE',
      cluster: 'CLUSTER',
      azAuth: 'AZ_AUTH',
      promUsername: 'PROM_USERNAME',
      promPassword: 'PROM_PASSWORD',
      azTenantId: 'AZ_TENANT_ID',
      azClientId: 'AZ_CLIENT_ID',
      azClientSecret: 'AZ_CLIENT_SECRET',
    };

    Object.entries(config).forEach(([key, value]) => {
      const envVarName = mappings[key];
      if (envVarName && value) {
        variables[`${prefix}_${envVarName}`] = value;
      }
    });
  });

  return variables;
}

/**
 * Generate Kubernetes ConfigMap YAML
 */
function generateConfigMapYaml(variables, configMapName = 'conduit-ui-config') {
  const sensitiveKeys = ['MASTER_KEY', 'AZ_CLIENT_SECRET', 'PROM_PASSWORD'];

  const configMapData = {};
  const secretData = {};

  Object.entries(variables).forEach(([key, value]) => {
    const isSensitive = sensitiveKeys.some(sensitiveKey =>
      key.includes(sensitiveKey)
    );

    if (isSensitive) {
      // Add to secrets (base64 encoded)
      secretData[key] = Buffer.from(value).toString('base64');
    } else {
      // Add to configmap
      configMapData[key] = value;
    }
  });

  let yaml = `apiVersion: v1
kind: ConfigMap
metadata:
  name: ${configMapName}
  namespace: conduit
data:
`;

  Object.entries(configMapData).forEach(([key, value]) => {
    yaml += `  ${key}: "${value}"\n`;
  });

  if (Object.keys(secretData).length > 0) {
    yaml += `---
apiVersion: v1
kind: Secret
metadata:
  name: conduit-ui-secrets
  namespace: conduit
type: Opaque
data:
`;
    Object.entries(secretData).forEach(([key, value]) => {
      yaml += `  ${key}: ${value}\n`;
    });
  }

  return yaml;
}

/**
 * Generate environment variables file
 */
function generateEnvFile(variables) {
  let envContent = '# Environment Configuration\n';
  envContent += '# Generated by migration script\n\n';

  Object.entries(variables).forEach(([key, value]) => {
    envContent += `${key}=${value}\n`;
  });

  return envContent;
}

/**
 * Validate environment configuration
 */
function validateConfiguration(variables) {
  const errors = [];
  const warnings = [];

  // Check for required fields
  const environments = new Set();
  Object.keys(variables).forEach(key => {
    if (key.includes('_API_BASE_URL')) {
      const envName = key.replace('_API_BASE_URL', '');
      environments.add(envName);
    }
  });

  environments.forEach(envName => {
    const prefix = envName.toUpperCase();
    const hasBaseUrl = variables[`${prefix}_API_BASE_URL`];
    const hasMasterKey = variables[`${prefix}_MASTER_KEY`];

    if (!hasBaseUrl) {
      errors.push(`Environment '${envName}' missing API_BASE_URL`);
    }
    if (!hasMasterKey) {
      errors.push(`Environment '${envName}' missing MASTER_KEY`);
    }
  });

  if (environments.size === 0) {
    errors.push('No environments found in configuration');
  }

  return { errors, warnings };
}

/**
 * Main migration function
 */
function migrate(jsonConfig) {
  try {
    logInfo('Starting environment configuration migration...');

    // Parse JSON configuration
    const environments = parseJsonConfig(jsonConfig);
    logSuccess(`Parsed ${Object.keys(environments).length} environments`);

    // Convert to prefixed variables
    const variables = convertToPrefixedVariables(environments);
    logSuccess(
      `Converted to ${Object.keys(variables).length} environment variables`
    );

    // Validate configuration
    const validation = validateConfiguration(variables);

    if (validation.errors.length > 0) {
      logError('Configuration validation failed:');
      validation.errors.forEach(error => logError(`  - ${error}`));
      return false;
    }

    if (validation.warnings.length > 0) {
      logWarning('Configuration warnings:');
      validation.warnings.forEach(warning => logWarning(`  - ${warning}`));
    }

    // Generate outputs
    const configMapYaml = generateConfigMapYaml(variables);
    const envContent = generateEnvFile(variables);

    // Write files
    const outputDir = path.join(process.cwd(), 'migration-output');
    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }

    fs.writeFileSync(path.join(outputDir, 'configmap.yaml'), configMapYaml);
    fs.writeFileSync(path.join(outputDir, '.env'), envContent);

    logSuccess('Migration completed successfully!');
    logInfo(`Output files created in: ${outputDir}`);
    logInfo('Files generated:');
    logInfo('  - configmap.yaml (Kubernetes ConfigMap and Secret)');
    logInfo('  - .env (Environment variables file)');

    return true;
  } catch (error) {
    logError(`Migration failed: ${error.message}`);
    return false;
  }
}

/**
 * CLI interface
 */
function main() {
  const args = process.argv.slice(2);

  if (args.length === 0) {
    logError('Usage: node migrate-env-config.js <json-config-string>');
    logInfo(
      'Example: node migrate-env-config.js \'{"production":{"baseUrl":"https://api.prod.com","masterKey":"key1"},"staging":{"baseUrl":"https://api.staging.com","masterKey":"key2"}}\''
    );
    process.exit(1);
  }

  const jsonConfig = args[0];
  const success = migrate(jsonConfig);
  process.exit(success ? 0 : 1);
}

// Run if called directly
if (require.main === module) {
  main();
}

module.exports = {
  migrate,
  parseJsonConfig,
  convertToPrefixedVariables,
  generateConfigMapYaml,
  generateEnvFile,
  validateConfiguration,
};
